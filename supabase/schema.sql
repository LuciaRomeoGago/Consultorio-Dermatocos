-- Dos turnos no pueden pisarse, los cargue la web o el panel.
create function public.turnos_sin_superposicion() returns trigger
language plpgsql set search_path = public as $$
declare
  v_ini int := split_part(new.hora, ':', 1)::int * 60 + split_part(new.hora, ':', 2)::int;
begin
  if new.estado = 'cancelado' or turno_vencido(new) then return new; end if;
  perform pg_advisory_xact_lock(hashtext('turnos' || new.dia::text));
  if exists (
    select 1 from turnos t
    where t.dia = new.dia and t.estado <> 'cancelado' and not turno_vencido(t) and t.id <> coalesce(new.id, -1)
      and v_ini < split_part(t.hora, ':', 1)::int * 60 + split_part(t.hora, ':', 2)::int + t.minutos
      and split_part(t.hora, ':', 1)::int * 60 + split_part(t.hora, ':', 2)::int < v_ini + new.minutos
  ) then
    raise exception 'horario_ocupado';
  end if;
  return new;
end $$;

create trigger turnos_sin_superposicion before insert or update on public.turnos
for each row execute function public.turnos_sin_superposicion();

-- Unidades comprometidas en reservas activas. Una rutina compromete cada producto que trae.
create view public.reservado with (security_invoker = true) as
select coalesce(ri.producto_id, i.producto_id) as producto_id, sum(i.qty)::int as qty
from reserva_items i
join reservas r on r.id = i.reserva_id and r.estado in ('nueva', 'esperando_stock', 'lista')
left join rutina_items ri on ri.rutina_id = i.producto_id
where i.producto_id is not null
group by 1;

create view public.v_stock with (security_invoker = true) as
select p.id, p.slug, p.name, p.category, p.img, p.stock, p.stock_min, p.ultimo_ingreso,
  coalesce(r.qty, 0) as reservado, p.stock - coalesce(r.qty, 0) as disponible
from productos p
left join reservado r on r.producto_id = p.id
where not p.es_rutina;

-- Unidades libres de un producto; para una rutina, las del producto que menos tiene.
create function public.disponible(p_id uuid) returns integer
language sql stable security definer set search_path = public as $$
  select coalesce(
    (select min(s.stock - coalesce(r.qty, 0))
       from rutina_items ri join productos s on s.id = ri.producto_id
       left join reservado r on r.producto_id = s.id
      where ri.rutina_id = p_id),
    (select p.stock - coalesce(r.qty, 0) from productos p left join reservado r on r.producto_id = p.id where p.id = p_id)
  )
$$;

