-- Quién puede entrar al panel: se agrega el mail a mano (ver README).
create table public.admins (email text primary key);

create table public.productos (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  word text not null default '',
  name text not null check (length(name) between 2 and 120),
  subtitle text not null default '',
  price integer check (price >= 0), -- null = "Consultar"
  category text not null check (category in ('Limpieza', 'Tónicos', 'Sérums', 'Hidratantes', 'Bálsamos', 'Máscaras', 'Rutinas')),
  img text not null,
  hover_img text,
  es_rutina boolean not null default false,
  stock integer not null default 0 check (stock >= 0),
  stock_min integer not null default 3 check (stock_min >= 0),
  visible boolean not null default true,
  ultimo_ingreso date,
  creado timestamptz not null default now()
);

create table public.rutina_items (
  rutina_id uuid not null references public.productos (id) on delete cascade,
  producto_id uuid not null references public.productos (id) on delete cascade,
  primary key (rutina_id, producto_id)
);

create table public.turnos (
  id bigint generated by default as identity primary key,
  dia date not null,
  hora text not null check (hora ~ '^\d{2}:\d{2}$'),
  minutos integer not null check (minutos between 15 and 240),
  tratamiento text not null check (length(tratamiento) between 2 and 120),
  nombre text not null check (length(nombre) between 2 and 120),
  telefono text not null check (length(telefono) <= 40),
  email text check (length(email) <= 160),
  nota text check (length(nota) <= 1000),
  estado text not null default 'por_confirmar' check (estado in ('por_confirmar', 'confirmado', 'cancelado')),
  origen text not null default 'web' check (origen in ('web', 'admin')),
  motivo text,
  -- Los turnos de la web se confirman con una seña del 25%; sin seña, a los 30 minutos dejan de ocupar el horario.
  sena_recibida boolean not null default false,
  creado timestamptz not null default now()
);
create index turnos_dia on public.turnos (dia);

-- Turno web sin seña que pasó el plazo: sigue en la agenda como "seña vencida" pero el horario queda libre.
-- Mismo plazo que SENA.minutos en src/lib/agenda.ts.
create function public.turno_vencido(t public.turnos) returns boolean
language sql stable set search_path = public as $$
  select t.origen = 'web' and t.estado = 'por_confirmar' and not t.sena_recibida and t.creado < now() - interval '30 minutes'
$$;

create table public.reservas (
  id bigint generated by default as identity (start with 1001) primary key,
  nombre text not null check (length(nombre) between 2 and 120),
  telefono text not null check (length(telefono) <= 40),
  email text check (length(email) <= 160),
  comentario text check (length(comentario) <= 1000),
  pago text not null check (pago in ('transferencia', 'efectivo')),
  pago_recibido boolean not null default false,
  estado text not null default 'nueva' check (estado in ('nueva', 'esperando_stock', 'lista', 'retirada', 'cancelada')),
  total integer not null default 0,
  creado timestamptz not null default now()
);

create table public.reserva_items (
  id bigint generated by default as identity primary key,
  reserva_id bigint not null references public.reservas (id) on delete cascade,
  -- Si se borra el producto, la reserva conserva nombre y precio.
  producto_id uuid references public.productos (id) on delete set null,
  nombre text not null,
  precio integer,
  qty integer not null check (qty between 1 and 10)
);
create index reserva_items_reserva on public.reserva_items (reserva_id);

create table public.ingresos (
  id bigint generated by default as identity primary key,
  producto_id uuid not null references public.productos (id) on delete cascade,
  unidades integer not null check (unidades between 1 and 10000),
  fecha date not null,
  nota text check (length(nota) <= 300),
  creado timestamptz not null default now()
);

-- Seguridad: solo los mails de `admins` leen y escriben. La web pública entra por las funciones de abajo.
create function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from admins where email = auth.jwt() ->> 'email')
$$;

