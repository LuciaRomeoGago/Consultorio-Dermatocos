create function public.catalogo()
returns table (slug text, word text, name text, subtitle text, price integer, category text, img text,
               hover_img text, es_rutina boolean, visible boolean, disponible integer)
language sql stable security definer set search_path = public as $$
  select p.slug, p.word, p.name, p.subtitle, p.price, p.category, p.img, p.hover_img, p.es_rutina, p.visible, disponible(p.id)
  from productos p order by p.creado, p.slug
$$;

-- Solo hora y duración: la web no ve quién tiene cada turno.
create function public.horarios_ocupados(p_dia date) returns table (hora text, minutos integer)
language sql stable security definer set search_path = public as $$
  select t.hora, t.minutos from turnos t where t.dia = p_dia and t.estado <> 'cancelado' and not turno_vencido(t)
$$;

create function public.reservar_turno(p_dia date, p_hora text, p_minutos integer, p_tratamiento text,
  p_nombre text, p_telefono text, p_email text default null, p_nota text default null)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_hoy date := (now() at time zone 'America/Argentina/Buenos_Aires')::date;
  v_ini int;
  v_id bigint;
  v_tel text := right(regexp_replace(coalesce(p_telefono, ''), '\D', '', 'g'), 10);
begin
  if p_hora !~ '^\d{2}:\d{2}$' or p_minutos not between 15 and 240
     or length(trim(coalesce(p_nombre, ''))) < 2
     or length(regexp_replace(coalesce(p_telefono, ''), '\D', '', 'g')) < 8 then
    raise exception 'datos_invalidos';
  end if;
  v_ini := split_part(p_hora, ':', 1)::int * 60 + split_part(p_hora, ':', 2)::int;
  -- Mismo horario que site.schedule en src/data/site.ts: lunes a viernes de 8 a 20, desde mañana.
  if p_dia <= v_hoy or p_dia > v_hoy + 90 or extract(isodow from p_dia) > 5
     or v_ini < 8 * 60 or v_ini + p_minutos > 20 * 60 then
    raise exception 'fuera_de_horario';
  end if;
  -- Contra turnos falsos: hasta 2 turnos activos por WhatsApp y 15 reservas web por día en total.
  if (select count(*) from turnos t
       where right(regexp_replace(t.telefono, '\D', '', 'g'), 10) = v_tel
         and t.dia >= v_hoy and t.estado <> 'cancelado' and not turno_vencido(t)) >= 2 then
    raise exception 'demasiados_turnos';
  end if;
  if (select count(*) from turnos where origen = 'web' and creado > now() - interval '24 hours') >= 15 then
    raise exception 'limite_diario';
  end if;
  insert into turnos (dia, hora, minutos, tratamiento, nombre, telefono, email, nota)
  values (p_dia, p_hora, p_minutos, trim(p_tratamiento), trim(p_nombre), trim(p_telefono),
          nullif(trim(coalesce(p_email, '')), ''), nullif(trim(coalesce(p_nota, '')), ''))
  returning id into v_id;
  return v_id;
end $$;

-- p_items: [{"slug": "acqua-di-jojoba", "qty": 1}, …]. Precios y stock salen de la base, no del navegador.
create function public.crear_reserva(p_nombre text, p_telefono text, p_email text, p_comentario text,
  p_pago text, p_items jsonb)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_id bigint;
  v_item jsonb;
  v_prod productos;
  v_qty int;
  v_total int := 0;
  v_falta boolean := false;
begin
  if length(trim(coalesce(p_nombre, ''))) < 2
     or length(regexp_replace(coalesce(p_telefono, ''), '\D', '', 'g')) < 8
     or p_pago not in ('transferencia', 'efectivo')
     or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) not between 1 and 20 then
    raise exception 'datos_invalidos';
  end if;
  insert into reservas (nombre, telefono, email, comentario, pago)
  values (trim(p_nombre), trim(p_telefono), nullif(trim(coalesce(p_email, '')), ''),
          nullif(trim(coalesce(p_comentario, '')), ''), p_pago)
  returning id into v_id;
  for v_item in select * from jsonb_array_elements(p_items) loop
    select * into v_prod from productos where slug = v_item ->> 'slug' and visible;
    if not found then raise exception 'producto_inexistente'; end if;
    v_qty := (v_item ->> 'qty')::int;
    if v_qty is null or v_qty not between 1 and 10 then raise exception 'datos_invalidos'; end if;
    if disponible(v_prod.id) < v_qty then v_falta := true; end if;
    insert into reserva_items (reserva_id, producto_id, nombre, precio, qty)
    values (v_id, v_prod.id, v_prod.name, v_prod.price, v_qty);
    v_total := v_total + coalesce(v_prod.price, 0) * v_qty;
  end loop;
  update reservas set total = v_total, estado = case when v_falta then 'esperando_stock' else 'nueva' end
  where id = v_id;
  return v_id;
end $$;

-- ── Funciones del panel ──

create function public.registrar_ingreso(p_producto uuid, p_unidades integer, p_fecha date, p_nota text)
returns void language plpgsql security invoker set search_path = public as $$
begin
  if not is_admin() then raise exception 'sin_permiso'; end if;
  insert into ingresos (producto_id, unidades, fecha, nota)
  values (p_producto, p_unidades, coalesce(p_fecha, current_date), nullif(trim(coalesce(p_nota, '')), ''));
  update productos
     set stock = stock + p_unidades,
         ultimo_ingreso = greatest(coalesce(ultimo_ingreso, p_fecha), coalesce(p_fecha, current_date))
   where id = p_producto and not es_rutina;
end $$;

-- Al entregar se descuenta del stock. Una rutina descuenta sus productos (según cómo está armada hoy).
create function public.marcar_retirada(p_id bigint) returns void
language plpgsql security invoker set search_path = public as $$
begin
  if not is_admin() then raise exception 'sin_permiso'; end if;
  update reservas set estado = 'retirada' where id = p_id and estado in ('nueva', 'esperando_stock', 'lista');
  if not found then raise exception 'estado_invalido'; end if;
  update productos p set stock = greatest(p.stock - d.qty, 0)
  from (
    select coalesce(ri.producto_id, i.producto_id) as pid, sum(i.qty)::int as qty
    from reserva_items i left join rutina_items ri on ri.rutina_id = i.producto_id
    where i.reserva_id = p_id and i.producto_id is not null
    group by 1
  ) d
  where p.id = d.pid;
end $$;

